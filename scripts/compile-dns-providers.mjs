#!/usr/bin/env node
// Compiles the per-provider DNS instructions from the support team's open source DNS checker
// (https://github.com/thunderbird/dns-scripts, MPL-2.0) into a typed module the frontend imports,
// so the app never has to fetch them at runtime.
//
// Usage: node scripts/compile-dns-providers.mjs <path/to/records.json> [source-commit]

import { readFileSync, writeFileSync } from 'node:fs';

const OUTPUT_PATH = new URL(
  '../assets/app/vue/views/CustomDomainsView/dnsProviders.generated.ts',
  import.meta.url
);

// records.json only carries provider ids, so the names shown to the user live here
const PROVIDER_LABELS = {
  namecheap: 'Namecheap',
  squarespace: 'Squarespace',
  cosmotown: 'Cosmotown',
  bunny: 'Bunny',
  spaceship: 'Spaceship',
  godaddy: 'GoDaddy',
  ionos: 'IONOS',
  ovh: 'OVH',
  hover: 'Hover',
  digitalocean: 'DigitalOcean',
  porkbun: 'Porkbun',
  'metanet-plesk': 'METANET (Plesk)',
  cloudflare: 'Cloudflare',
};

// The provider used when the user's isn't listed: plain "type / name / value" instructions
const GENERIC_PROVIDER_ID = 'generic';
const RECORD_TYPES = ['MX', 'SRV', 'TXT', 'CNAME'];

// Blocks that haven't been confirmed end to end start with a note meant for the maintainers
const publicHeader = (header) => {
  if (!header.startsWith('UNVERIFIED')) {
    return header;
  }
  const cut = header.indexOf('. ');
  return cut === -1 ? header.replace(/^UNVERIFIED\s*—\s*/, '') : header.slice(cut + 2);
};

const [recordsPath, sourceCommit = 'unknown'] = process.argv.slice(2);
if (!recordsPath) {
  console.error('Usage: node scripts/compile-dns-providers.mjs <path/to/records.json> [source-commit]');
  process.exit(1);
}

const source = JSON.parse(readFileSync(recordsPath, 'utf-8'));

const compileProvider = (id, instructions) => ({
  id,
  label: id === GENERIC_PROVIDER_ID ? 'Other' : (PROVIDER_LABELS[id] ?? id),
  records: Object.fromEntries(
    RECORD_TYPES.map((type) => [
      type,
      {
        header: publicHeader(instructions[type].header),
        fields: instructions[type].fields.map(([label, template]) => ({ label, template })),
      },
    ])
  ),
});

const providers = Object.entries(source.providers)
  .filter(([id]) => id !== GENERIC_PROVIDER_ID)
  .map(([id, instructions]) => compileProvider(id, instructions))
  .sort((a, b) => a.label.localeCompare(b.label));

providers.push(compileProvider(GENERIC_PROVIDER_ID, source.providers[GENERIC_PROVIDER_ID]));

// One field per line keeps the generated file readable and its diffs small
const formatField = (field) => `          { label: ${JSON.stringify(field.label)}, template: ${JSON.stringify(field.template)} },`;

const formatInstructions = ({ header, fields }) => `{
        header: ${JSON.stringify(header)},
        fields: [
${fields.map(formatField).join('\n')}
        ],
      }`;

const formatProvider = (provider) => `  {
    id: ${JSON.stringify(provider.id)},
    label: ${JSON.stringify(provider.label)},
    records: {
${RECORD_TYPES.map((type) => `      ${type}: ${formatInstructions(provider.records[type])},`).join('\n')}
    },
  },`;

const output = `// Generated by scripts/compile-dns-providers.mjs from records.json in
// https://github.com/thunderbird/dns-scripts (MPL-2.0), commit ${sourceCommit}. Do not edit by hand.
import type { DnsProviderConfig } from './types';

export const GENERIC_DNS_PROVIDER_ID = '${GENERIC_PROVIDER_ID}';

export const DNS_PROVIDERS: DnsProviderConfig[] = [
${providers.map(formatProvider).join('\n')}
];
`;

writeFileSync(OUTPUT_PATH, output);
console.log(`Wrote ${providers.length} providers to ${OUTPUT_PATH.pathname}`);
